#把一组重复测量的浓度数据存成一个列表： 0.1021, 0.1018, 0.1035, 0.1012, 0.1029
import numpy as np
a = np.array([0.1021, 0.1018, 0.1035, 0.1012, 0.1029])

print(f"数组：{a}")
print(f"数组形状：{a.shape}")  # 查看数组的形状
print(f"数据类型：{a.dtype}")  # 查看数组的数据类型
print(f"元素个数：{a.size}")   # 查看数组中元素的个数
print(f"最大值：{a.max():.4f}")  # 查看数组中的最大值
print(f"最小值：{a.min():.4f}")  # 查看数组中的最小值
print(f"平均值：{a.mean():.4f}")  # 查看数组的平均值
print(f"极差：{a.max() - a.min():.4f}")  # 查看数组的极差
print(f"乘以1000后的数组：{a*1000}")  # 数组中每个元素乘以1000