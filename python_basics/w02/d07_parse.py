#背景：你从仪器导出的记录经常是这样的（注意多余的空格）：
#record = "  S-01 , 0.1021 , 25.3  "
#任务：把它拆成 3 个干净的值并打印出来：
#代码块
#样品名: S-01
#浓度: 0.1021
#温度: 25.3
#要求：打印出来的值不能带多余空格。
#两个工具：
#方法	作用	返回什么
#.strip()	去掉首尾空格	字符串
#.split(",")	按逗号拆开	列表
#⚠️ 关键点：
#拆完之后，每个元素还带着空格（比如 ' 0.1021 '）。 所以你需要再处理一遍。
#想想该怎么写 —— 拆开之后是个列表，你要对列表里每个元素做同一件事……
#（是不是又想起 for 循环了？）
record = "  S-01 , 0.1021 , 25.3  "
record = record.strip()
values = record.split(",")
for i in range(len(values)):
    values[i] = values[i].strip()
print("样品名:", values[0])
print("浓度:", values[1])
print("温度:", values[2])
